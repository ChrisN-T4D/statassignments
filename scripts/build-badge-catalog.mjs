/**
 * Builds the one list of badges that both the server (what counts as earned) and the app (how to show it) read:
 * backend/lib/badge_catalog.json for the server and src/data/badgeCatalog.generated.js for the app (same content). Run `node scripts/build-badge-catalog.mjs` after changing objectives, modules,
 * objective badge names, or the module-badge thresholds below. `--check` fails if the committed file is stale.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { statisticsModules } from '../src/data/modules.js'
import { getObjectivesByModule } from '../src/data/objectives.js'
import { getQuestionsForObjective } from '../src/data/questionObjectiveMap.js'
import { OBJECTIVE_BADGE_NAMES } from '../src/data/objectiveBadgeNames.js'

/** A module badge (gold) is earned when this share of the module's objective badges are earned. Edit freely. */
export const MODULE_BADGE_SHARE = 0.75

const MODULE_BADGE_NAMES = {
  'stats-module-1': 'Why Stats Mastery',
  'stats-module-2': 'Research Design Mastery',
  'stats-module-3': 'Software Basics Mastery',
  'stats-module-4': 'Descriptives Mastery',
  'stats-module-5': 'Visualization Mastery',
  'stats-module-6': 'Probability Mastery',
  'stats-module-7': 'Hypothesis Testing Mastery',
  'stats-module-8': 'Analysis Methods Mastery'
}

const MATH_TOPICS = [
  ['M0-O1', 'Order of operations', '( )'],
  ['M0-O2', 'Solving for a variable', 'x='],
  ['M0-O3', 'Fractions, decimals, percents', '%'],
  ['M0-O4', 'Exponents and roots', '√'],
  ['M0-O5', 'Summation', 'Σ'],
  ['M0-O6', 'Reading graphs', '↗'],
  ['M0-O7', 'Algebra symbols', '±']
]

export function buildCatalog() {
  const modules = [
    {
      id: 'stats-module-0',
      class_id: 'statistics',
      title: 'Math Refresher',
      path: '/class/statistics/math-practice',
      // Math Refresher badges come from Math Practice and its Mastery Check (backend/api/awards.py, kind "math")
      kind: 'math',
      module_badge: { award_id: 'math-module:stats-module-0', name: 'Math Ready', glyph: '★', min_count: MATH_TOPICS.length, min_state: 'checked' },
      topics: MATH_TOPICS.map(([objective, name, glyph]) => ({
        award_id: `math-topic:${objective}`,
        objective_id: objective,
        name,
        glyph,
        problem_prefix: `m0-${objective}-`
      }))
    }
  ]
  for (const mod of statisticsModules) {
    if (mod.isBenchmark || mod.number == null || mod.number < 1) continue
    const objectives = getObjectivesByModule(mod.id)
    if (!objectives.length) continue
    const topics = objectives.map((o, index) => {
      const name = OBJECTIVE_BADGE_NAMES[o.objectiveId]
      if (!name) throw new Error(`No badge name for ${o.objectiveId}`)
      return {
        award_id: `objective:${o.objectiveId}`,
        objective_id: o.objectiveId,
        name,
        glyph: String(index + 1),
        type: o.objectiveType,
        items: getQuestionsForObjective(o.objectiveId).length
      }
    })
    modules.push({
      id: mod.id,
      class_id: 'statistics',
      title: mod.shortTitle,
      full_title: mod.title,
      path: `/class/statistics?module=${mod.id}`,
      kind: 'objectives',
      module_badge: {
        award_id: `module:${mod.id}`,
        name: MODULE_BADGE_NAMES[mod.id] || `${mod.shortTitle} Mastery`,
        glyph: '★',
        min_count: Math.ceil(topics.length * MODULE_BADGE_SHARE),
        min_state: 'earned'
      },
      topics
    })
  }
  return {
    version: 1,
    rules: { mastery_pl: 0.9, streak: 3, default_items: 3 },
    modules
  }
}

const here = path.dirname(fileURLToPath(import.meta.url))
const target = path.join(here, '..', 'backend', 'lib', 'badge_catalog.json')
const targetJs = path.join(here, '..', 'src', 'data', 'badgeCatalog.generated.js')

export function catalogJs(catalog) {
  return `// Generated by scripts/build-badge-catalog.mjs from the course data. Do not edit by hand.\nexport default ${JSON.stringify(catalog, null, 2)}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalog = buildCatalog()
  const text = JSON.stringify(catalog, null, 2) + '\n'
  const js = catalogJs(catalog)
  if (process.argv.includes('--check')) {
    const stale = [[target, text], [targetJs, js]].filter(([file, want]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== want)
    if (stale.length) {
      console.error('Badge catalog is out of date: run node scripts/build-badge-catalog.mjs')
      process.exit(1)
    }
    console.log('badge catalog is up to date')
  } else {
    fs.writeFileSync(target, text)
    fs.writeFileSync(targetJs, js)
    console.log(`wrote ${target} and ${targetJs}: ${catalog.modules.length} modules, ${catalog.modules.reduce((n, m) => n + m.topics.length, 0)} objective badges`)
    for (const m of catalog.modules) console.log(`  ${m.id}: ${m.topics.length} badges, module badge at ${m.module_badge.min_count} (${m.module_badge.min_state})`)
  }
}
